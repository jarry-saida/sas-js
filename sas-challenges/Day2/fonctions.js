//Une fonction est un bloc de code réutilisable qui permet d'effectuer une tâche précise ou de calculer une valeur
// les paramètres sont les variables écrites dans la définition d'une fonction
// tandis que les arguments sont les valeurs réelles transmises lors de l'appel
// et return permet de renvoyer un résultat
// si aucun return n'est écrit, la fonction renvoie undefined
function direBonjour(nom) {
  return "Bonjour " + nom;
}// dirBonjour est le nom de fonction
//nom est un parametre l
// Appel de la fonction
let message = direBonjour("saida"); 
// alice est l'arguments
