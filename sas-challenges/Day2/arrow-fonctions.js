//Une fonction fléchée (arrow function en anglais) est une syntaxe plus courte pour écrire des expressions de fonction
//écrit sans le mot-clé function, en plaçant une flèche => entre les paramètres et le corps de la fonction
// Fonction classique
const addition1 = function(a, b) {
  return a + b;
};

// Fonction fléchée équivalente
const addition2 = (a, b) => {
  return a + b;
};